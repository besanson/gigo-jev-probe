def deterministic_sentence_indices(sentences: list[str], seed: str, k: int = 10) -> list[int]:
    n = len(sentences)
    if n == 0:
        return []
    idxs, i = [], 0
    while len(idxs) < min(k, n):
        cand = int(hashlib.sha256(f"{seed}:{i}".encode()).hexdigest(), 16) % n
        if cand not in idxs:
            idxs.append(cand)
        i += 1
    return sorted(idxs)


def split_sentences(text: str) -> list[str]:
    text = re.sub(r"(?m)^[ \t]*-[ \t]+", "\n\n", text)
    out = []
    for para in re.split(r"\n\s*\n", text):
        if re.search(r"[_^]|>=|<=|\bmax\b|\bmin\b|\bsum\b|[≤≥Σ∑]", para):
            continue
        if len(re.findall(r"  {2,}", para)) >= 2:
            continue
        para = normalize_ws(para)
        if not para:
            continue
        for s in re.split(r"(?<=[.!?])\s+(?=[A-Z(\[])", para):
            s = s.strip()
            if len(s) <= 20 or sum(c.isalpha() for c in s) / len(s) <= 0.5:
                continue
            if re.search(r"-{4,}", s):
                continue
            out.append(s)
    return out


def front_matter_check() -> dict:
    fm = md_front_matter()
    tex = MAIN_TEX.read_text(encoding="utf-8")
    title_m = re.search(r"\\title\{([^\n]*)\}", tex)
    author_m = re.search(r"\\author\{(.*?)\\thanks\{([^\n}]*)\}\}", tex)
    md_title = run(["pandoc", "-f", "markdown", "-t", "latex", "--wrap=none"], input=fm.get("title", "")).stdout.strip()
    checks = {
        "title": (md_title, title_m.group(1).strip() if title_m else ""),
        "author_name": (fm.get("author", ""), author_m.group(1).strip() if author_m else ""),
        "affiliation": (fm.get("thanks", ""), author_m.group(2).strip() if author_m else ""),
    }
    out = {k: {"md": a, "tex": b, "match": bool(a) and a == b} for k, (a, b) in checks.items()}
    return {"pass": all(v["match"] for v in out.values()), **out}


_IDENTIFIER_RE = re.compile(r"`[^`]+`|\bCH-?[A-Z]?\d+\b|\b[a-z_][a-z0-9_.-]*\.(?:py|json|jsonl|md)\b")


def _sentence_content_tokens(sentence: str) -> dict:
    return {"numbers": NUMBER_RE.findall(sentence),
            "identifiers": [i for i in (m.strip("`") for m in _IDENTIFIER_RE.findall(sentence)) if i]}


def gate_g4_prose_parity() -> dict:
    md_slices, pdf_slices = md_section_slices(), pdf_section_slices()
    sections, all_within = {}, True
    for title in SECTION_TITLES:
        md_wc, pdf_wc = word_count(md_slices.get(title, "")), word_count(pdf_slices.get(title, ""))
        pct = pdf_wc / md_wc * 100 if md_wc else None
        within = (pdf_wc == 0) if md_wc == 0 else SECTION_WORD_RATIO_MIN_PCT <= pct <= SECTION_WORD_RATIO_MAX_PCT
        all_within = all_within and within and md_wc > 0
        sections[title] = {"md_words": md_wc, "pdf_words": pdf_wc,
                           "pct_of_source": round(pct, 3) if pct is not None else None, "within_band": within}

    metadata = front_matter_check()
    sentences = split_sentences(md_plain())
    source_sha256 = hashlib.sha256(SOURCE_MD.read_bytes()).hexdigest()
    idxs = deterministic_sentence_indices(sentences, source_sha256, k=10)
    pdf_norm = normalize_ws(extract_pdf_text_layout_full())
    pdf_flat = pdf_norm.replace(" ", "")
    sample = []
    for i in idxs:
        s = sentences[i]
        tokens = _sentence_content_tokens(s)
        missing_numbers = [n for n in tokens["numbers"] if n not in pdf_norm]
        missing_ids = [x for x in tokens["identifiers"] if x.replace(" ", "") not in pdf_flat]
        sample.append({"index": i, "sentence": s[:160], **tokens, "missing_numbers": missing_numbers,
                       "missing_identifiers": missing_ids, "found": not missing_numbers and not missing_ids})
    ok = all_within and metadata["pass"] and all(r["found"] for r in sample)
    return {"pass": ok, "source_sha256": source_sha256,
            "section_word_ratio_band_pct": [SECTION_WORD_RATIO_MIN_PCT, SECTION_WORD_RATIO_MAX_PCT],
            "sections": sections, "front_matter_metadata_check": metadata, "sentence_sample": sample}



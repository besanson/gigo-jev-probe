CITE_PLACEHOLDER_PATTERN = re.compile(r"\[CITE[-:][^\]]*\]")
PANDOC_CITE_RE = re.compile(r"@([A-Za-z0-9][A-Za-z0-9_:.-]*[A-Za-z0-9])")


def cited_keys(text: str) -> set[str]:
    keys = set()
    for group in re.findall(r"\[([^\]]*@[^\]]*)\]", text):
        keys.update(PANDOC_CITE_RE.findall(group))
    return keys


def gate_g8_citation_completeness() -> dict:
    text = SOURCE_MD.read_text(encoding="utf-8")
    placeholders = CITE_PLACEHOLDER_PATTERN.findall(text)
    verified = {c["id"] for c in json.loads(CITATIONS_JSON.read_text(encoding="utf-8"))["citations"]}
    keys = cited_keys(text)
    citation_check = _load_module("citation_check", PAPER_TEX_DIR / "citation_check.py")
    tokens = citation_check.check(str(SOURCE_MD), str(CITATIONS_JSON))
    unknown, uncited = sorted(keys - verified), sorted(verified - keys)
    return {"pass": not placeholders and not unknown and not uncited and tokens["clean"],
            "cite_placeholder_count": len(placeholders), "cite_placeholders": placeholders,
            "cited_keys": sorted(keys), "keys_not_verified": unknown, "verified_but_uncited": uncited,
            "citation_check_tokens_clean": tokens["clean"]}



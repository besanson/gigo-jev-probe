def normalize_ws(text: str) -> str:
    text = dehyphenate(text)
    text = text.replace("\u00ad", "")
    for uni, ascii_ in _QUOTE_NORMALIZE.items():
        text = text.replace(uni, ascii_)
    text = re.sub(r"'\s+([,)])", r"'\1", text)
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"\s*_\s*", "_", text)
    text = re.sub(r"\s+\)", ")", text)
    text = re.sub(r"\s+:", ":", text)
    return text.strip()


def _slices(text: str, anchors: list[str], end_anchor: str | None) -> dict[str, str]:
    positions, search_from = [], 0
    for anchor in anchors + ([end_anchor] if end_anchor else []):
        idx = text.find(anchor, search_from)
        positions.append(idx)
        if idx != -1:
            search_from = idx + len(anchor)
    out = {}
    for pos, title in enumerate(anchors):
        start = positions[pos]
        end = next((p for p in positions[pos + 1:] if p != -1), None)
        out[title] = "" if start == -1 else (text[start:end] if end else text[start:])
    return out


def md_section_slices() -> dict[str, str]:
    """filters/number-sections.lua numbers the plain rendering exactly as LaTeX numbers the PDF."""
    return _slices(normalize_ws(md_plain(numbered=True)), SECTION_TITLES, "Acknowledgements")


def pdf_section_slices() -> dict[str, str]:
    return _slices(normalize_ws(extract_pdf_text_layout_full()), SECTION_TITLES, "Acknowledgements")


def word_count(text: str) -> int:
    return len(normalize_ws(text).split())



TAG_PHRASES = ["machine-checked", "checked-scope-only", "pending-human-review"]


def _load_module(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, str(path))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def used_slots() -> dict[str, str]:
    """The slots the manuscript actually uses, with their values (paper/populate.py)."""
    populate = _load_module("paper6_populate", REPO_ROOT / "paper" / "populate.py")
    return populate.used_slot_values(DRAFT_MD.read_text(encoding="utf-8"))


def _slot_numbers(slots: dict[str, str]) -> dict[str, list[str]]:
    by_number: dict[str, list[str]] = {}
    for name, value in slots.items():
        for tok in NUMBER_RE.findall(normalize_number_words(str(value))):
            by_number.setdefault(tok, []).append(name)
    return by_number


def _verbatim_numbers(md_text: str) -> set[str]:
    """Numbers inside the manuscript's code spans, code blocks and quotations: verbatim registered
    text (prompts, question wording, banks), which the PDF prints as ordinary text."""
    spans = re.findall(r"```.*?```|`[^`\n]*`|\"[^\"\n]*\"", md_text, re.DOTALL)
    return {n for s in spans for n in NUMBER_RE.findall(s)}


def gate_g3_number_parity() -> dict:
    typed_numerals = _load_module("typed_numerals", REPO_ROOT / "lint" / "typed_numerals.py")
    raw_pdf = dehyphenate(extract_pdf_text())
    for uni, ascii_ in _QUOTE_NORMALIZE.items():
        raw_pdf = raw_pdf.replace(uni, ascii_)
    pdf_text = normalize_number_words(raw_pdf)
    pdf_numbers = set(NUMBER_RE.findall(pdf_text))
    slots = used_slots()
    slot_numbers = _slot_numbers(slots)

    # Forward: every number a used slot carries is printed somewhere in the paper (digits or
    # words).
    missing_from_pdf = {tok: names for tok, names in slot_numbers.items() if tok not in pdf_numbers}

    # Reverse: every digit number the PDF prints is a slot number, verbatim registered text, or
    # survives the typed-numerals allowlist (structural numbers, identifiers, registered design
    # parameters). Number words are not typed numerals and are not checked in this direction.
    verbatim = _verbatim_numbers(SOURCE_MD.read_text(encoding="utf-8"))
    residual = typed_numerals.residual_numbers(raw_pdf, pdf=True)
    unexplained_in_pdf = sorted({tok for tok in residual if tok not in slot_numbers and tok not in verbatim})

    md_text = SOURCE_MD.read_text(encoding="utf-8")
    tag_counts = {p: {"source_count": md_text.count(p), "pdf_count": pdf_text.count(p)} for p in TAG_PHRASES}
    tags_ok = all((v["pdf_count"] > 0) == (v["source_count"] > 0) for v in tag_counts.values())

    return {
        "pass": not missing_from_pdf and not unexplained_in_pdf and tags_ok,
        "used_slot_count": len(slots),
        "slot_number_count": len(slot_numbers),
        "slot_numbers_missing_from_pdf": missing_from_pdf,
        "pdf_numbers_not_in_slots_or_registered": unexplained_in_pdf,
        "tag_counts": tag_counts,
    }



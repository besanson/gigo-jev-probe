# G9: Bibliography quality (ported schema checks; audit file per citation)
# ---------------------------------------------------------------------------

VALID_ENTRY_TYPES = {"article", "inproceedings", "incollection", "misc"}
REQUIRED_VENUE_FIELDS_BY_TYPE = {"article": ("journal",), "inproceedings": ("booktitle",), "incollection": ("booktitle",)}
TRUNCATED_AUTHOR_RE = re.compile(r"\bet al\b|\bothers\b|\.\.\.", re.IGNORECASE)


def gate_g9_bibliography_quality() -> dict:
    citations = json.loads(CITATIONS_JSON.read_text(encoding="utf-8"))["citations"]
    refs_bib_text = REFS_BIB.read_text(encoding="utf-8") if REFS_BIB.exists() else ""
    audit = json.loads(BIB_AUDIT_JSON.read_text(encoding="utf-8")) if BIB_AUDIT_JSON.exists() else {"results": []}
    audit_by_id = {r["id"]: r for r in audit.get("results", [])}
    problems: dict[str, list] = {k: [] for k in (
        "invalid_entry_type", "missing_authors", "truncated_author_list", "missing_venue_fields",
        "doi_mismatches", "misc_with_venue_info", "audit_missing", "audit_failed")}
    for c in citations:
        cid, entry_type = c.get("id", "<no id>"), c.get("entry_type")
        if entry_type not in VALID_ENTRY_TYPES:
            problems["invalid_entry_type"].append({"id": cid, "entry_type": entry_type})
            continue
        authors = c.get("authors")
        if not authors or c.get("first_author") != authors[0]:
            problems["missing_authors"].append({"id": cid})
        elif any(TRUNCATED_AUTHOR_RE.search(a) for a in authors):
            problems["truncated_author_list"].append({"id": cid, "authors": authors})
        for field in REQUIRED_VENUE_FIELDS_BY_TYPE.get(entry_type, ()):
            if not c.get(field):
                problems["missing_venue_fields"].append({"id": cid, "missing_field": field})
        if "doi" in c and f"doi = {{{c['doi']}}}" not in refs_bib_text:
            problems["doi_mismatches"].append({"id": cid, "doi": c["doi"]})
        if entry_type == "misc" and (c.get("journal") or c.get("booktitle")):
            problems["misc_with_venue_info"].append({"id": cid})
        record = audit_by_id.get(cid)
        if record is None:
            problems["audit_missing"].append(cid)
        elif not record.get("pass"):
            problems["audit_failed"].append({"id": cid, "detail": record.get("mismatches")})
    grb = _load_module("generate_refs_bib", PAPER_TEX_DIR / "generate_refs_bib.py")
    refs_bib_matches = refs_bib_text == grb.generate()
    ok = refs_bib_matches and not any(problems.values())
    return {"pass": ok, "total_citations": len(citations), "refs_bib_matches_generator": refs_bib_matches,
            "audited": len(audit_by_id), **problems}



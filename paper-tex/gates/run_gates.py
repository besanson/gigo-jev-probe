def gate_g5_structure_parity() -> dict:
    md = md_body()
    tex = MAIN_TEX.read_text(encoding="utf-8")
    md_counts = {
        "sections": len(re.findall(r"^# \S", md, re.MULTILINE)),
        "subsections": len(re.findall(r"^## \S", md, re.MULTILINE)),
        "tables": len(re.findall(r"^\|[\s:|-]+\|\s*$", md, re.MULTILINE)),
        "figures": len(re.findall(r"^!\[", md, re.MULTILINE)),
        "propositions": len(re.findall(r"\*\*(?:Proposition S\d|N6)\b", md)),
        "footnotes": len(re.findall(r"^\[\^\w+\]:", md, re.MULTILINE)) + (1 if md_front_matter().get("thanks") else 0),
    }
    tex_counts = {
        "sections": len(re.findall(r"^\\section\*?\{", tex, re.MULTILINE)),
        "subsections": len(re.findall(r"^\\subsection\*?\{", tex, re.MULTILINE)),
        "tables": len(re.findall(r"^\\begin\{longtable\}", tex, re.MULTILINE)),
        "figures": len(re.findall(r"\\includegraphics", tex)),
        "propositions": len(re.findall(r"\\textbf\{(?:Proposition S\d|N6)\b", tex)),
        "footnotes": len(re.findall(r"\\footnote\{", tex)) + len(re.findall(r"\\thanks\{", tex)),
    }
    counts = {k: {"source": md_counts[k], "tex": tex_counts[k], "equal": md_counts[k] == tex_counts[k]} for k in md_counts}
    return {"pass": all(v["equal"] for v in counts.values()), "counts": counts}



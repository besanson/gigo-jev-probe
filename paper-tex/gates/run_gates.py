def _trim_bibliography(text: str) -> str:
    """Everything from the References heading on is bibtex output, not manuscript prose.

    Paper 6 keeps its appendices before the bibliography, so they stay in."""
    m = re.search(r"[\n\x0c]\s*References\s*[\n\x0c]", text)
    return text[:m.start()] if m else text


def _strip_page_footers(text: str) -> str:
    return "\n".join(line for line in text.splitlines() if not re.fullmatch(r"\s*\d+\s*", line))


def _strip_repeated_page_furniture(text: str) -> str:
    """Remove a running header: a first line repeated on at least half the pages (positional)."""
    pages = text.split("\x0c")
    if len(pages) < 3:
        return text
    first_lines = []
    for p in pages:
        candidates = [line for line in p.splitlines() if line.strip()]
        first_lines.append(candidates[0].strip() if candidates else None)
    threshold = max(3, len(pages) // 2)
    furniture = {line for line, n in Counter(x for x in first_lines if x is not None).items() if n >= threshold}
    if not furniture:
        return text
    out_pages = []
    for p in pages:
        lines = p.splitlines()
        idx = next((i for i, line in enumerate(lines) if line.strip()), None)
        if idx is not None and lines[idx].strip() in furniture:
            lines = lines[:idx] + lines[idx + 1:]
        out_pages.append("\n".join(lines))
    return "\x0c".join(out_pages)


def extract_pdf_text() -> str:
    """Layout extraction, running header and bibliography removed, page footers stripped (G3)."""
    r = run(["pdftotext", "-layout", str(MAIN_PDF), "-"])
    text = _strip_repeated_page_furniture(r.stdout)
    text = _trim_bibliography(text)
    return _strip_page_footers(text)


def extract_pdf_text_reflow() -> str:
    """Reflowed extraction of the full document (G6)."""
    r = run(["pdftotext", str(MAIN_PDF), "-"])
    return _strip_page_footers(_strip_repeated_page_furniture(r.stdout))


def extract_pdf_text_layout_full() -> str:
    """Layout extraction of the full document, page footers stripped (G4)."""
    r = run(["pdftotext", "-layout", str(MAIN_PDF), "-"])
    return _strip_page_footers(_strip_repeated_page_furniture(r.stdout))


def md_body(path: Path = SOURCE_MD) -> str:
    """The manuscript without its YAML front matter."""
    text = path.read_text(encoding="utf-8")
    if text.startswith("---\n"):
        text = text[text.index("\n---\n", 4) + 5:]
    return text


def md_front_matter(path: Path = SOURCE_MD) -> dict:
    import yaml

    text = path.read_text(encoding="utf-8")
    return yaml.safe_load(text[4:text.index("\n---\n", 4)]) if text.startswith("---\n") else {}


def md_plain(numbered: bool = False) -> str:
    numbering = ["--lua-filter", str(PAPER_TEX_DIR / "filters" / "number-sections.lua")]
    cmd = ["pandoc", "-f", "markdown", "-t", "plain", "--wrap=none"] + (numbering if numbered else [])
    return run(cmd, input=md_body()).stdout


NUMBER_RE = re.compile(
    r"\b\d{1,3}(?:,\d{3})+(?:\.\d+)?(?!\d)"    # 15,120 / 27,000
    r"|\b\d+\.\d+(?:[eE][-+]?\d+)?(?!\d)"      # 6.124 / 1.69e-21
    r"|\b\d+[eE][-+]?\d+(?!\d)"                # bare scientific notation
    r"|\b\d+(?!\d)"                            # plain integers
)


def dehyphenate(text: str) -> str:
    text = re.sub(r"-\n\s*(?=[a-z])", "-", text)
    return re.sub(r"([eE][-+])\n\s*(?=\d)", r"\1", text)


def extract_numbers(text: str) -> Counter:
    return Counter(NUMBER_RE.findall(dehyphenate(text)))


_ONES = {
    "zero": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5,
    "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10,
    "eleven": 11, "twelve": 12, "thirteen": 13, "fourteen": 14, "fifteen": 15,
    "sixteen": 16, "seventeen": 17, "eighteen": 18, "nineteen": 19,
}
_TENS = {"twenty": 20, "thirty": 30, "forty": 40, "fifty": 50, "sixty": 60, "seventy": 70, "eighty": 80, "ninety": 90}
_SCALES = {"hundred": 100, "thousand": 1000, "million": 1000000}
_NUMBER_WORDS = set(_ONES) | set(_TENS) | set(_SCALES)
_WORD_ALT = "|".join(sorted(_NUMBER_WORDS, key=len, reverse=True))
_NUMBER_WORD_RUN_RE = re.compile(rf"\b(?:{_WORD_ALT})(?:[\s-]+(?:{_WORD_ALT}))*\b", re.IGNORECASE)


def _number_words_to_int(words: list[str]) -> int:
    total = current = 0
    for w in (x.lower() for x in words):
        if w in _ONES:
            current += _ONES[w]
        elif w in _TENS:
            current += _TENS[w]
        elif w == "hundred":
            current = (current or 1) * 100
        elif w in ("thousand", "million"):
            total += (current or 1) * _SCALES[w]
            current = 0
    return total + current


# Font and extraction artifacts, not content (ported table).
_QUOTE_NORMALIZE = {
    "‘": "'", "’": "'", "“": '"', "”": '"', "∗": "*", "′": "'", "–": "--",
    "ﬀ": "ff", "ﬁ": "fi", "ﬂ": "fl", "ﬃ": "ffi", "ﬄ": "ffl", "−": "-",
}


def normalize_number_words(text: str) -> str:
    for uni, ascii_ in _QUOTE_NORMALIZE.items():
        text = text.replace(uni, ascii_)

    def repl(m: re.Match) -> str:
        n = _number_words_to_int(re.split(r"[\s-]+", m.group(0)))
        return f"{n:,}" if n >= 1000 else str(n)

    return _NUMBER_WORD_RUN_RE.sub(repl, text)



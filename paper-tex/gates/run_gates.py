def gate_table(results: dict) -> str:
    rows = ["| gate | result |", "|---|---|"]
    rows += [f"| {name} | {'PASS' if g['pass'] else 'FAIL'} |" for name, g in results.items()]
    return "\n".join(rows)


def main(argv: list[str] | None = None) -> int:
    args = sys.argv[1:] if argv is None else argv
    names = [a for a in args if a in GATES] or list(GATES)
    results = {name: GATES[name]() for name in names}
    all_pass = all(g["pass"] for g in results.values())
    if names == list(GATES):
        report = {"all_pass": all_pass, "gates": results}
        REPORT_PATH.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    for name, g in results.items():
        if not g["pass"]:
            print(f"--- {name} detail ---")
            print(json.dumps(g, indent=2, sort_keys=True)[:6000])
    print(gate_table(results))
    print("ALL GATES PASS" if all_pass else "GATE FAILURE -- see detail above")
    return 0 if all_pass else 1


